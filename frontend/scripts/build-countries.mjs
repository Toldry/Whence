/**
 * Writes src/data/countries.generated.ts: every country that has at least one
 * searchable airport in the back end's bundled reference data, with the UN M49
 * subregion it belongs to. Run it after refreshing the reference data:
 *   node scripts/build-countries.mjs
 *
 * Sources:
 * - Country names and airports: backend/src/data/reference.json (Travelpayouts).
 * - Regions: the UN geoscheme (M49), via
 *   https://github.com/lukes/ISO-3166-Countries-with-Regional-Codes
 *   For Latin America and Sub-Saharan Africa the finer "intermediate" region is
 *   used (South America, Western Africa...), so no group is continent-sized.
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const REFERENCE = path.join(here, '../../backend/src/data/reference.json');
const OUTPUT = path.join(here, '../src/data/countries.generated.ts');
const UN_CSV_URL =
  'https://raw.githubusercontent.com/lukes/ISO-3166-Countries-with-Regional-Codes/master/all/all.csv';

/** Codes Travelpayouts uses that ISO 3166 / M49 does not list. */
const EXTRA_SUBREGIONS = {
  XK: 'Southern Europe', // Kosovo
  AB: 'Western Asia', // Abkhazia, as Georgia
  KX: 'Eastern Europe', // Crimea, as Ukraine
  NY: 'Southern Europe', // Northern Cyprus, as Cyprus below
  TW: 'Eastern Asia', // Taiwan; the CSV leaves its region blank
};
/**
 * Deliberate departures from M49, where travellers would not look for a country
 * under its UN group. M49 puts Cyprus in Western Asia; it is an EU member.
 */
const SUBREGION_OVERRIDES = { CY: 'Southern Europe' };
/** Friendlier or current short names. The reference name stays searchable as an alias. */
const NAME_OVERRIDES = { TR: 'Türkiye', CZ: 'Czechia', TL: 'Timor-Leste' };

function parseCsvLine(line) {
  const cells = [];
  let cell = '';
  let quoted = false;
  for (const char of line) {
    if (char === '"') quoted = !quoted;
    else if (char === ',' && !quoted) { cells.push(cell); cell = ''; }
    else cell += char;
  }
  cells.push(cell);
  return cells;
}

const slug = (name) => name.toLowerCase().replace(/[^a-z]+/g, '-').replace(/^-|-$/g, '');

const response = await fetch(UN_CSV_URL);
if (!response.ok) throw new Error(`UN regions CSV: HTTP ${response.status}`);
const [header, ...lines] = (await response.text()).trim().split(/\r?\n/);
const columns = parseCsvLine(header);
const column = (name) => columns.indexOf(name);
const subregionByCode = {};
for (const line of lines) {
  const cells = parseCsvLine(line);
  const code = cells[column('alpha-2')];
  const intermediate = cells[column('intermediate-region')];
  const subregion = cells[column('sub-region')];
  // Channel Islands is an intermediate region of Northern Europe; keep it there.
  const useIntermediate = subregion === 'Latin America and the Caribbean' || subregion === 'Sub-Saharan Africa';
  const name = useIntermediate && intermediate ? intermediate : subregion;
  if (name) subregionByCode[code] = name;
}
Object.assign(subregionByCode, EXTRA_SUBREGIONS, SUBREGION_OVERRIDES);

const reference = JSON.parse(await readFile(REFERENCE, 'utf8'));
const withAirport = new Set(reference.airports.filter((a) => a[6] === 1).map((a) => a[3]));
const rows = [];
const missing = [];
for (const [code, referenceName] of Object.entries(reference.countries)) {
  if (!withAirport.has(code)) continue;
  const subregion = subregionByCode[code];
  if (!subregion) { missing.push(`${code} ${referenceName}`); continue; }
  rows.push([code, NAME_OVERRIDES[code] ?? referenceName, slug(subregion)]);
}
if (missing.length) throw new Error(`No UN subregion for: ${missing.join(', ')}`);
rows.sort((a, b) => a[1].localeCompare(b[1], 'en'));

const body = rows.map((row) => `  ${JSON.stringify(row)},`).join('\n');
await writeFile(OUTPUT, `// Generated by scripts/build-countries.mjs. Do not edit by hand.
/** [ISO 3166 alpha-2 code, English name, subregion key from regions.ts] */
export const COUNTRY_ROWS: [string, string, string][] = [
${body}
];
`);
console.log(`Wrote ${path.relative(process.cwd(), OUTPUT)}: ${rows.length} countries`);
